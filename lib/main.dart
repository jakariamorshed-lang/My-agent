import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:http/http.dart' as http;
import 'package:shared_preferences/shared_preferences.dart';
import 'package:url_launcher/url_launcher.dart';

void main() {
  runApp(const MaterialApp(
    debugShowCheckedModeBanner: false,
    title: 'KajKori Personal Agent',
    home: AgentDashboard(),
  ));
}

class AgentDashboard extends StatefulWidget {
  const AgentDashboard({super.key});
  @override
  State<AgentDashboard> createState() => _AgentDashboardState();
}

class _AgentDashboardState extends State<AgentDashboard> {
  final TextEditingController _taskController = TextEditingController(
    text: "YouTube Shorts Make: AI Phone Tricks (via WhatsApp Muse AI & Thumbnail)",
  );
  final List<String> _logs = [];
  bool _isProcessing = false;
  Map<String, dynamic>? _agentResult;

  final Map<String, bool> _appPermissions = {
    'WhatsApp (Muse AI Chat Bridge)': true,
    'YouTube Studio (Auto Upload Short)': true,
    'CapCut / Video Synthesizer': true,
    'Phone Gallery & Storage': true,
  };

  void _addLog(String msg) {
    setState(() {
      _logs.insert(0, "[${DateTime.now().toString().substring(11, 19)}] $msg");
    });
  }

  Future<void> _openPhoneAppIntent(String urlScheme, String fallbackWeb, String appLabel) async {
    _addLog("ফোনের অ্যাপ ওপেন করা হচ্ছে: $appLabel...");
    final uri = Uri.parse(urlScheme);
    if (await canLaunchUrl(uri)) {
      await launchUrl(uri, mode: LaunchMode.externalApplication);
    } else {
      await launchUrl(Uri.parse(fallbackWeb), mode: LaunchMode.externalApplication);
    }
  }

  Future<void> _runAgent() async {
    final task = _taskController.text.trim();
    if (task.isEmpty) {
      _addLog("অনুগ্রহ করে একটি টাস্ক লিখুন!");
      return;
    }

    final prefs = await SharedPreferences.getInstance();
    final apiKey = prefs.getString('gemini_key') ?? '';
    if (apiKey.isEmpty) {
      _addLog("সতর্কতা: উপরের Settings (⚙️) আইকনে গিয়ে আপনার Gemini API Key দিন!");
      return;
    }

    setState(() {
      _isProcessing = true;
      _agentResult = null;
    });

    _addLog("টাস্ক গ্রহণ করা হয়েছে: $task");
    _addLog("Step 1/4: WhatsApp চ্যাট লিস্টের Muse AI-কে প্রম্পট পাঠানো হচ্ছে...");

    try {
      final models = ['gemini-2.5-flash', 'gemini-flash-latest'];
      http.Response? res;
      Map<String, dynamic>? data;

      final prompt = '''
You are KajKori Personal Agent. The user task is: "$task".
Connected phone permissions: ${_appPermissions.entries.where((e) => e.value).map((e) => e.key).join(', ')}.
Return ONLY valid JSON with these keys:
{
  "musePrompt": "Prompt sent to WhatsApp Muse AI",
  "shortsTitle": "Viral YouTube Shorts Title",
  "thumbnailHeadline": "BOLD 3-WORD THUMBNAIL TEXT",
  "thumbnailSub": "Subtitle for 9:16 cover",
  "script": "Complete 4-scene YouTube Shorts script with voiceover and timestamps in Bengali/Banglish",
  "whatsappShareText": "Ready script & thumbnail generated by Personal Agent"
}
''';

      for (final m in models) {
        final url = Uri.parse(
          'https://generativelanguage.googleapis.com/v1beta/models/$m:generateContent?key=$apiKey',
        );
        res = await http.post(
          url,
          headers: {'Content-Type': 'application/json'},
          body: jsonEncode({
            "contents": [
              {
                "parts": [
                  {"text": prompt}
                ]
              }
            ],
            "generationConfig": {"responseMimeType": "application/json"}
          }),
        );
        data = jsonDecode(res.body);
        if (res.statusCode == 200) {
          _addLog("মডেল সফলভাবে কানেক্ট হয়েছে: $m");
          break;
        }
      }

      if (res != null && res.statusCode == 200 && data?['candidates'] != null) {
        final rawText = data!['candidates'][0]['content']['parts'][0]['text'];
        final parsed = jsonDecode(rawText) as Map<String, dynamic>;
        setState(() {
          _agentResult = parsed;
        });
        _addLog("Step 2/4: Muse AI থেকে স্ক্রিপ্ট ও 9:16 থাম্বনেইল তৈরি সম্পন্ন!");
        _addLog("Step 3/4: ফোনের পারমিশন অনুযায়ী অটোমেটিক অ্যাপ ব্রিজ প্রস্তুত!");
        _addLog("Step 4/4: নিচে 1-Click বাটনে চাপ দিয়ে WhatsApp বা YouTube Studio-তে পাঠিয়ে দিন!");
      } else {
        final errorMsg = data?['error']?['message'] ?? 'API Error (${res?.statusCode})';
        _addLog("API এরর: $errorMsg");
      }
    } catch (e) {
      _addLog("ব্যর্থ হয়েছে: $e");
    } finally {
      setState(() => _isProcessing = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFF0F172A),
      appBar: AppBar(
        title: const Text("KajKori Personal Agent"),
        backgroundColor: const Color(0xFF1E293B),
        foregroundColor: Colors.white,
        actions: [
          IconButton(
            icon: const Icon(Icons.settings),
            onPressed: () => Navigator.push(
              context,
              MaterialPageRoute(builder: (_) => const SettingsPage()),
            ),
          )
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            TextField(
              controller: _taskController,
              maxLines: 2,
              style: const TextStyle(color: Colors.white),
              decoration: const InputDecoration(
                labelText: "আপনার টাস্ক লিখুন (যেমন: YouTube Shorts Make & Upload)",
                labelStyle: TextStyle(color: Colors.amber),
                enabledBorder: OutlineInputBorder(borderSide: BorderSide(color: Colors.white24)),
                focusedBorder: OutlineInputBorder(borderSide: BorderSide(color: Colors.amber)),
              ),
            ),
            const SizedBox(height: 12),
            SizedBox(
              width: double.infinity,
              height: 48,
              child: ElevatedButton.icon(
                onPressed: _isProcessing ? null : _runAgent,
                icon: const Icon(Icons.play_arrow),
                label: Text(_isProcessing ? "এজেন্ট কাজ করছে..." : "অটোমেটেড টাস্ক শুরু করুন"),
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.amber,
                  foregroundColor: Colors.black,
                ),
              ),
            ),
            const SizedBox(height: 16),
            if (_agentResult != null) ...[
              Container(
                width: double.infinity,
                padding: const EdgeInsets.all(14),
                decoration: BoxDecoration(
                  color: const Color(0xFF1E293B),
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(color: Colors.amber.withValues(alpha: 0.5)),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      "9:16 THUMBNAIL: ${_agentResult!['thumbnailHeadline'] ?? ''}",
                      style: const TextStyle(color: Colors.amber, fontWeight: FontWeight.bold, fontSize: 16),
                    ),
                    const SizedBox(height: 4),
                    Text(
                      "Title: ${_agentResult!['shortsTitle'] ?? ''}",
                      style: const TextStyle(color: Colors.white, fontWeight: FontWeight.w600),
                    ),
                    const Divider(color: Colors.white24, height: 20),
                    Text(
                      _agentResult!['script'] ?? '',
                      style: const TextStyle(color: Colors.white70, fontSize: 13, height: 1.4),
                    ),
                    const SizedBox(height: 12),
                    Wrap(
                      spacing: 8,
                      runSpacing: 8,
                      children: [
                        ElevatedButton.icon(
                          onPressed: () => _openPhoneAppIntent(
                            "whatsapp://send?text=${Uri.encodeComponent(_agentResult!['musePrompt'] ?? '')}",
                            "https://wa.me/",
                            "WhatsApp Muse AI",
                          ),
                          icon: const Icon(Icons.chat, size: 16),
                          label: const Text("Open WhatsApp Muse AI"),
                          style: ElevatedButton.styleFrom(backgroundColor: Colors.green.shade700, foregroundColor: Colors.white),
                        ),
                        ElevatedButton.icon(
                          onPressed: () => _openPhoneAppIntent(
                            "vnd.youtube.creator://",
                            "https://studio.youtube.com",
                            "YouTube Studio",
                          ),
                          icon: const Icon(Icons.video_call, size: 16),
                          label: const Text("Upload in YouTube Studio"),
                          style: ElevatedButton.styleFrom(backgroundColor: Colors.red.shade700, foregroundColor: Colors.white),
                        ),
                      ],
                    )
                  ],
                ),
              ),
              const SizedBox(height: 16),
            ],
            const Text("ফোনের অ্যাপ পারমিশন (App Permissions):", style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold)),
            ..._appPermissions.keys.map((appKey) => SwitchListTile(
                  dense: true,
                  contentPadding: EdgeInsets.zero,
                  title: Text(appKey, style: const TextStyle(color: Colors.white70, fontSize: 13)),
                  value: _appPermissions[appKey] ?? true,
                  activeColor: Colors.amber,
                  onChanged: (val) => setState(() => _appPermissions[appKey] = val),
                )),
            const SizedBox(height: 8),
            const Text("অ্যাকশন লগ:", style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold)),
            const SizedBox(height: 6),
            Container(
              width: double.infinity,
              height: 180,
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: Colors.black,
                borderRadius: BorderRadius.circular(10),
              ),
              child: ListView.builder(
                itemCount: _logs.length,
                itemBuilder: (_, i) => Padding(
                  padding: const EdgeInsets.symmetric(vertical: 2),
                  child: Text(_logs[i], style: const TextStyle(color: Colors.greenAccent, fontSize: 12, fontFamily: 'monospace')),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class SettingsPage extends StatefulWidget {
  const SettingsPage({super.key});
  @override
  State<SettingsPage> createState() => _SettingsPageState();
}

class _SettingsPageState extends State<SettingsPage> {
  final _keyController = TextEditingController();

  @override
  void initState() {
    super.initState();
    SharedPreferences.getInstance().then((p) {
      _keyController.text = p.getString('gemini_key') ?? '';
    });
  }

  void _save() async {
    final key = _keyController.text.trim();
    final p = await SharedPreferences.getInstance();
    await p.setString('gemini_key', key);
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text("API Key সফলভাবে সংরক্ষিত হয়েছে!")),
      );
      Navigator.pop(context);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFF0F172A),
      appBar: AppBar(title: const Text("Settings"), backgroundColor: const Color(0xFF1E293B), foregroundColor: Colors.white),
      body: Padding(
        padding: const EdgeInsets.all(16.0),
        child: Column(
          children: [
            TextField(
              controller: _keyController,
              style: const TextStyle(color: Colors.white),
              decoration: const InputDecoration(
                labelText: "Google Gemini API Key",
                labelStyle: TextStyle(color: Colors.amber),
                border: OutlineInputBorder(),
              ),
            ),
            const SizedBox(height: 16),
            ElevatedButton(
              onPressed: _save,
              style: ElevatedButton.styleFrom(backgroundColor: Colors.amber, foregroundColor: Colors.black),
              child: const Text("Save Key"),
            ),
          ],
        ),
      ),
    );
  }
}
